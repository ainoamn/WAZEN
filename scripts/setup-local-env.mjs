#!/usr/bin/env node
/**
 * Generates a local .env.local with strong random secrets for development.
 * Does not overwrite an existing .env.local unless --force is passed.
 */
import { randomBytes } from "node:crypto";
import { existsSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const target = path.join(root, ".env.local");
const force = process.argv.includes("--force");

if (existsSync(target) && !force) {
  console.log(".env.local already exists. Pass --force to overwrite.");
  process.exit(0);
}

const key = randomBytes(32).toString("base64");
const contents = `# Generated by scripts/setup-local-env.mjs — local development only
# For Vercel production use Turso + secrets from docs/PRODUCTION-DEPLOYMENT.md

WAZEN_USE_NODE_SQLITE=1
WAZEN_DEMO_MODE=0
WAZEN_TRUST_OAI_HEADERS=0
WAZEN_APP_ORIGIN=http://localhost:3000
# BHD_IDENTITY_ISSUER=https://id.bhd-om.com
# BHD_OAUTH_CLIENT_ID=bhd-wazen
# BHD_OAUTH_CLIENT_SECRET=
# BHD_OAUTH_REDIRECT_URI=http://localhost:3000/api/auth/bhd/callback
WAZEN_ADMIN_EMAILS=admin@wazen.pro
WAZEN_PAYMENT_WEBHOOK_SECRET=${randomBytes(32).toString("hex")}
WAZEN_JOB_SECRET=${randomBytes(32).toString("hex")}
WAZEN_ENCRYPTION_KEYRING={"active":"v1","keys":{"v1":"${key}"}}
WAZEN_EMAIL_PROVIDER_HOSTS=localhost
WAZEN_PAYMENT_PROVIDER_HOSTS=localhost
`;

writeFileSync(target, contents, "utf8");
console.log(`Wrote ${target}`);
console.log("Next: npm run db:migrate && npm run dev");
